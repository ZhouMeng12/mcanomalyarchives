"""Deterministic Minecraft-style material atlas for the procedural poppy mesh."""
from pathlib import Path
from PIL import Image
import math
import random

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'src/main/resources/assets/mcanomalyarchives/textures/entity/poppy_illusion.png'

def main():
    image = Image.new('RGBA', (64, 32), (0, 0, 0, 0))
    rng = random.Random(150003)
    for tile in range(5):
        for y in range(16):
            for x in range(16):
                nx, ny = (x-7.5)/8, (y-7.5)/8
                radius, angle = math.hypot(nx, ny), math.atan2(ny, nx)
                grain = rng.uniform(-1, 1)
                patch = math.sin((x//3)*1.7 + (y//3)*2.1)
                if tile == 0:
                    fold = max(0, math.sin(angle*8 + radius*3))**6
                    light = .88 + grain*.13 + patch*.07 - fold*.14
                    rgb = (239*light, (39+radius*5)*light, (29+radius*3)*light)
                elif tile == 1:
                    ridge = math.sin(x*.75)*.055 + math.sin(x*.22)*.06
                    node = .12 if (y//3)%8 == 0 else 0
                    light = .94+ridge+grain*.05-node
                    rgb = (43*light,145*light,48*light)
                elif tile == 2:
                    vein = .17 if abs(ny) < .06 or abs(abs(ny)-abs(nx)*.65)% .20 < .035 else 0
                    light = .92 + grain*.04 + patch*.035 - vein
                    rgb = (32*light,111*light,45*light)
                elif tile == 3:
                    groove = max(0,math.sin(radius*37+math.sin(angle*9)))**8
                    light = .65+min(1,radius)*.35 + grain*.08-groove*.2
                    rgb = (72*light,15*light,14*light)
                else:
                    light = .88+y/16*.12+grain*.025
                    root = max(0,1-y/6)*.12
                    rgb = (244*light,245*light-root*25,235*light-root*35)
                # A small discrete palette keeps the material close to vanilla pixel art.
                rgb=tuple(round(v/8)*8 for v in rgb)
                image.putpixel(((tile%4)*16+x,(tile//4)*16+y),tuple(max(0,min(255,round(v))) for v in rgb)+(255,))
    TARGET.parent.mkdir(parents=True,exist_ok=True)
    atlas=Image.new('RGBA',(256,256),(0,0,0,0))
    atlas.paste(image.resize((256,128),Image.Resampling.NEAREST),(0,0))
    head=Image.open(ROOT/'tools/assets/source/poppy-head.png').convert('RGBA')
    atlas.paste(head.resize((128,128),Image.Resampling.NEAREST),(128,128))
    atlas.save(TARGET)
    # The silhouette is part of the model, giving the drawn head real side walls.
    mask=head.resize((48,48),Image.Resampling.NEAREST).getchannel('A')
    rows=[]
    for y in range(48):
        bits=sum(1<<x for x in range(48) if mask.getpixel((x,y))>=192)
        rows.append(f'0x{bits:012x}L')
    outline=ROOT/'src/main/java/net/mcreator/mcanomalyarchives/anomaly/poppy/PoppyFlowerOutline.java'
    outline.write_text('package net.mcreator.mcanomalyarchives.anomaly.poppy;\n\n'
        '/** Generated by tools/assets/generate_poppy_material.py from the approved flower artwork. */\n'
        'final class PoppyFlowerOutline {\n    static final int SIZE=48;\n    static final long[] ROWS={\n        '
        +',\n        '.join(','.join(rows[n:n+6]) for n in range(0,48,6))
        +'\n    };\n    static boolean filled(int x,int y) {\n'
        '        return x>=0&&x<SIZE&&y>=0&&y<SIZE&&(ROWS[y]&(1L<<x))!=0;\n'
        '    }\n    private PoppyFlowerOutline() {}\n}\n',encoding='utf-8')
    print(TARGET)

if __name__ == '__main__':
    main()
